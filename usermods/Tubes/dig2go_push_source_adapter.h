// Bounded, non-autonomous orchestration for exactly one operator-enrolled target.
// All exits after pause pass through restoration before exposing failure.
class Dig2GoPushBridgeRuntime {
public:
  explicit Dig2GoPushBridgeRuntime(Dig2GoPushBridgeHooks& hooks) : _hooks(hooks) {}

  bool joinPassed() const { return _joinPassed; }
  bool httpPassed() const { return _gatewayPassed; }
  Dig2GoSourceAdapterResult inspectionResult() const { return _inspectionResult; }

  bool arm(const uint8_t targetMac[6], uint32_t timeoutMs) {
    if (_state != PushBridgeIdle || !knownMac(targetMac) || timeoutMs == 0
        || timeoutMs > 0x7FFFFFFFU)
      return false;
    memcpy(_admission.enrolledMac, targetMac, 6);
    _admission.legacyRelease = 13;
    _deadline = _hooks.now() + timeoutMs;
    _state = PushBridgeTargetAdmitted;
    if (!_hooks.sendLegacyV15Selection(targetMac)) return fail(false);
#if defined(TUBES_DIG2GO_READINESS_DELAY_TEST)
    _readyAt = _hooks.now() + 5000;
    _state = PushBridgeReadinessDelay;
#endif
    return true;
  }

  void update() {
    if (_state == PushBridgeIdle || _state == PushBridgeHealthy || _state == PushBridgeFailed)
      return;
    if (!active()) { fail(_paused); return; }
#if defined(TUBES_DIG2GO_READINESS_DELAY_TEST)
    if (_state == PushBridgeReadinessDelay) {
      if (static_cast<int32_t>(_readyAt - _hooks.now()) > 0) return;
      _state = PushBridgeTargetAdmitted;
    }
#endif
    switch (_state) {
      case PushBridgeTargetAdmitted:
        if (!_hooks.pauseTubesRadio()) { fail(false); return; }
        _paused = true;
        _state = PushBridgeMeshPaused;
        if (!_hooks.beginExclusiveWledJoin()) fail(true);
        return;
      case PushBridgeMeshPaused:
        if (!_hooks.updateAccessPointConnected()) return;
        _joinPassed = true;
        _state = PushBridgeApJoined;
#if defined(TUBES_DIG2GO_READINESS_DELAY_TEST)
        _associated = true;
        _localIpPassed = _hooks.updateAccessPointHasLocalIp();
        _gatewayPassed = _hooks.updateAccessPointHasGateway();
        if (_localIpPassed && _gatewayPassed) {
          _joinPassed = true;
          _diagnosticSuccessPending = true;
          _state = PushBridgeRestoringMesh;
          restore(false);
        }
        return;
#elif defined(TUBES_DIG2GO_STEP3_DIAGNOSTIC)
        // Diagnostic compatibility path is intentionally not used by the test.
        _joinPassed = _hooks.updateAccessPointConnected();
        if (!_joinPassed) { fail(true); return; }
        _diagnosticSuccessPending = true;
        _state = PushBridgeRestoringMesh;
        restore(false);
        return;
#else
        _inspectionDeadline = _hooks.now() + 15000;
        _nextInspectionAt = _hooks.now();
        return;
#endif
      case PushBridgeApJoined:
#if !defined(TUBES_DIG2GO_READINESS_DELAY_TEST) && !defined(TUBES_DIG2GO_STEP3_DIAGNOSTIC)
        if (static_cast<int32_t>(_nextInspectionAt - _hooks.now()) > 0) return;
        _inspectionResult = _hooks.inspectSelectedTarget(_admission, _evidence);
        if (_inspectionResult == Dig2GoSourceAdapterHttpFailed
            && static_cast<int32_t>(_inspectionDeadline - _hooks.now()) > 0) {
          _nextInspectionAt = _hooks.now() + 1000;
          return;
        }
        if (_inspectionResult != Dig2GoSourceAdapterAccepted) { fail(true); return; }
        _gatewayPassed = true;
#if defined(TUBES_DIG2GO_INSPECTION_ONLY_TEST)
        _diagnosticSuccessPending = true;
        _state = PushBridgeRestoringMesh;
        restore(false);
        return;
#else
        _state = PushBridgeUploading;
        if (_hooks.uploadActiveImage() != FirmwarePostAccepted) { fail(true); return; }
        _uploadFinishedAt = _hooks.now();
        _state = PushBridgeRestoringMesh;
        restore(false);
        return;
#endif
#endif
        return;
      case PushBridgeRestoringMesh:
        restore(false);
        return;
      default:
        return;
    }
  }

  bool observeFreshV15Health(const uint8_t mac[6], uint32_t observedAt) {
    if (_state != PushBridgeAwaitingHealth || !mac
        || memcmp(mac, _admission.enrolledMac, 6) != 0
        || static_cast<int32_t>(observedAt - _uploadFinishedAt) <= 0
        || !active())
      return false;
    _state = PushBridgeHealthy;
    return true;
  }

  PushBridgeState state() const { return _state; }
  bool batonReady() const { return _state == PushBridgeHealthy; }
  PushBridgeOverlay overlay() const {
    if (_state == PushBridgeTargetAdmitted || _state == PushBridgeMeshPaused || _state == PushBridgeApJoined)
      return PushOverlayReady;
    if (_state == PushBridgeUploading || _state == PushBridgeRestoringMesh || _state == PushBridgeAwaitingHealth)
      return PushOverlayTransfer;
    if (_state == PushBridgeHealthy) return PushOverlayComplete;
    if (_state == PushBridgeFailed) return PushOverlayFailed;
    return PushOverlayNone;
  }

private:
  static bool knownMac(const uint8_t mac[6]) {
    if (!mac) return false;
    uint8_t combined = 0;
    for (size_t index = 0; index < 6; index++) combined |= mac[index];
    return combined != 0;
  }
  bool active() const { return static_cast<int32_t>(_deadline - _hooks.now()) > 0; }
  bool fail(bool restoreRequired) {
    if (restoreRequired) {
      _failurePending = true;
      _state = PushBridgeRestoringMesh;
      restore(true);
    } else {
      _state = PushBridgeFailed;
    }
    return false;
  }
  void restore(bool failed) {
    if (!_paused || _hooks.restoreTubesRadio()) {
      _paused = false;
      const bool finalFailure = failed || _failurePending;
      _failurePending = false;
      const bool diagnosticSuccess = _diagnosticSuccessPending;
      _diagnosticSuccessPending = false;
      _state = finalFailure ? PushBridgeFailed
          : diagnosticSuccess ? PushBridgeHealthy : PushBridgeAwaitingHealth;
    }
  }

  Dig2GoPushBridgeHooks& _hooks;
  Dig2GoTargetAdmission _admission;
  LegacyDig2GoEvidence _evidence;
  uint32_t _deadline = 0;
#if defined(TUBES_DIG2GO_READINESS_DELAY_TEST)
  uint32_t _readyAt = 0;
#endif
  uint32_t _uploadFinishedAt = 0;
#if !defined(TUBES_DIG2GO_READINESS_DELAY_TEST) && !defined(TUBES_DIG2GO_STEP3_DIAGNOSTIC)
  uint32_t _inspectionDeadline = 0;
  uint32_t _nextInspectionAt = 0;
#endif
  PushBridgeState _state = PushBridgeIdle;
  Dig2GoSourceAdapterResult _inspectionResult = Dig2GoSourceAdapterHttpFailed;
  bool _paused = false;
  bool _failurePending = false;
  bool _diagnosticSuccessPending = false;
  bool _joinPassed = false;
#if defined(TUBES_DIG2GO_READINESS_DELAY_TEST)
  bool _associated = false;
  bool _localIpPassed = false;
  bool _gatewayPassed = false;
#else
  bool _gatewayPassed = false;
#endif
};

