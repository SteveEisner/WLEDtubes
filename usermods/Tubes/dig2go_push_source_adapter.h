// Test-only boot gate: readiness must be observed after the delay, and the
// callback is latched before invocation so failures and timeouts cannot retry.
class Dig2GoAutoTrigger {
public:
  explicit Dig2GoAutoTrigger(uint32_t delayMs = 15000) : _delayMs(delayMs) {}
  bool maybeStart(uint32_t now, bool meshReady, bool& attempted) {
    if (_attempted || attempted || !meshReady || static_cast<int32_t>(now - _bootAt) < static_cast<int32_t>(_delayMs)) return false;
    _attempted = true;
    attempted = true;
    return true;
  }
  void booted(uint32_t now) { _bootAt = now; _attempted = false; }
  bool attempted() const { return _attempted; }
private:
  uint32_t _bootAt = 0;
  uint32_t _delayMs;
  bool _attempted = false;
};

struct Dig2GoJsonFacts {
  uint8_t observedMac[6] = {0};
  bool selectedUpdateState = false;
  bool classicEsp32 = false;
  uint16_t ledTotal = 0;
  uint16_t outputLength = 0;
  uint8_t outputCount = 0;
  uint8_t pin = 0xFF;
  uint8_t type = 0;
  uint8_t order = 0xFF;
  uint8_t start = 0xFF;
  uint8_t skip = 0xFF;
  bool reversed = true;
};

inline bool admitDig2GoJsonFacts(
    const Dig2GoTargetAdmission& admission,
    const Dig2GoJsonFacts& facts
) {
  const bool knownLegacyImplicitBus = facts.outputCount == 0 && facts.ledTotal == 300;
  const bool explicitDig2GoBus = facts.outputCount == 1
      && (facts.ledTotal == 112 || facts.ledTotal == 150)
      && facts.outputLength == facts.ledTotal
      && facts.pin == 16 && facts.type == 22 && facts.order == 0
      && facts.start == 0 && facts.skip == 0 && !facts.reversed;
  return admission.legacyRelease == 13
      && memcmp(admission.enrolledMac, facts.observedMac, 6) == 0
      && facts.selectedUpdateState && facts.classicEsp32
      && (knownLegacyImplicitBus || explicitDig2GoBus);
}

inline bool useLegacyConfigFallback(int primaryStatus) {
  return primaryStatus == 404 || primaryStatus == 405;
}

