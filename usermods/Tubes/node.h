    // AI: below section was generated by an AI
    // A received serial character proves that a host is listening more reliably
    // than the external USB-UART bridge's reset-oriented modem-control signals.
    void renewSerialTrace() {
        bool wasEnabled = serialTraceEnabled();
        serialTraceExpiresAt = millis() + SERIAL_TRACE_LEASE_MS;
        if (!wasEnabled)
            Serial.println();
    }

    bool serialTraceEnabled() const {
        return serialTraceExpiresAt != 0
            && int32_t(serialTraceExpiresAt - millis()) > 0;
    }
