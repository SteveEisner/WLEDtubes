    void sendCommand(
        CommandId command,
        const void *data,
        uint8_t len,
        const V3ProjectionTrailer* projectionTrailer = nullptr
    ) {
        // if (!ESP_NOW.isStarted()) {
        //     Serial.println("SendCommand ESP Not Started!");
        //     return;
        // }
        if (len > MESSAGE_DATA_SIZE) {
            Serial.printf("Message is too big: %d vs %d\n",
                len, MESSAGE_DATA_SIZE);
            return;
        }
        if (projectionTrailer && len > V3_PROJECTION_TRAILER_OFFSET) {
            Serial.printf("Legacy command overlaps projection trailer: %d\n", len);
            return;
        }

        NodeMessage message;
        message.header = legacyHeader();
        if (command == COMMAND_INFO) {
            message.recipients = RECIPIENTS_NEIGHBORS;
        } else if (command == COMMAND_STATE) {
            message.recipients = RECIPIENTS_ALL;
        } else if (isFollowing()) {
            // Follower nodes must request that the root re-sends this message
            message.recipients = RECIPIENTS_ROOT;
        } else {
            message.recipients = RECIPIENTS_ALL;
        }
        message.command = command;
        if (len > 0)
            memcpy(&message.data, data, len);
        if (projectionTrailer)
            writeV3ProjectionTrailer(message, *projectionTrailer);
#ifdef NODE_DEBUGGING
        Serial.println("sendCommand");
#endif
        broadcastMessage(&message);
    }

    // AI: below section was generated by an AI
    // Send one validated v3 topic through the same root-oriented routing tree as v2.
    bool sendV3Topic(uint8_t topic, const V3TopicPayload& payload) {
        if (!isValidV3TopicPayload(topic, payload)) {
            Serial.printf("Invalid v3 topic payload: %02X\n", topic);
            return false;
        }

        NodeMessage message;
        message.header = nativeHeader();
        bool neighborsOnly = topic == V3TopicPresence
            || (topic == V3TopicPosition && payload.envelope.messageKind == V3Advertisement);
        if (neighborsOnly)
            message.recipients = RECIPIENTS_NEIGHBORS;
        else if (isFollowing())
            message.recipients = RECIPIENTS_ROOT;
        else
            message.recipients = RECIPIENTS_ALL;
        message.command = topic;
        memcpy(message.data, &payload, sizeof(payload));
        broadcastMessage(&message);
        return true;
    }

    // Send one channel packet over the shared Control tree.
    bool sendV3Channel(uint8_t channel, const TubesChannelPayload& payload) {
        if (!isValidTubesChannelPayload(channel, payload)) {
            Serial.printf("Invalid v3 channel payload: %02X\n", channel);
            return false;
        }

        NodeMessage message;
        message.header = nativeHeader();
        if (payload.envelope.messageKind == ControlBeacon)
            message.recipients = RECIPIENTS_NEIGHBORS;
        else if (payload.envelope.messageKind == ChannelDeclaration)
            message.recipients = RECIPIENTS_ALL;
        else if (isFollowing())
            message.recipients = RECIPIENTS_ROOT;
        else
            return false;
        message.command = channel;
        memcpy(message.data, &payload, sizeof(payload));
        broadcastMessage(&message);
        return true;
    }

    // Send one variable-length channel snapshot after the complete packet has
    // passed the same ingress validation used by receivers.
    bool sendV3ChannelV2(uint8_t channel, TubesChannelMessageV2& message) {
        message.header = nativeHeader();
        message.command = channel;
        if (message.envelope.messageKind == ChannelDeclaration) {
            if (isFollowing())
                return false;
            message.recipients = RECIPIENTS_ALL;
        } else if (message.envelope.messageKind == ChannelRequest && isFollowing()) {
            message.recipients = RECIPIENTS_ROOT;
        } else {
            return false;
        }
        message.timebase = strip.timebase + millis();
        size_t length = channelMessageV2WireSize(message.envelope.bodyLength);
        if (!isValidChannelMessageV2Prefix(
                reinterpret_cast<const uint8_t*>(&message), length)) {
            Serial.printf("Invalid variable v3 channel: %02X\n", channel);
            return false;
        }
        return espnowBroadcast.send(reinterpret_cast<const uint8_t*>(&message), length);
    }
