    void printMessage(const NodeMessage* message, signed int rssi) const {
        Serial.printf("%04X/%04X v%d ",
            message->header.id,
            message->header.uplinkId,
            message->header.version
        );
        if (message->header.version == TUBES_PROTOCOL_V3)
            Serial.printf("TOPIC-%02X", message->command);
        else
            Serial.print(command_name(message->command));
        if (message->header.version == TUBES_PROTOCOL_V3 && isKnownTubesChannel(message->command)) {
            const TubesChannelPayload& payload = *reinterpret_cast<const TubesChannelPayload*>(message->data);
            Serial.printf("[%04X/%04X k%u s%u]",
                payload.envelope.channelId,
                payload.envelope.sourceControlId,
                payload.envelope.messageKind,
                payload.envelope.sequence
            );
        }
        if (message->recipients == RECIPIENTS_ROOT)
            Serial.printf(":ROOT");
        if (rssi)
            Serial.printf(" %ddB ", rssi);
    }

    // AI: below section was generated by an AI
    void onPeerData(const uint8_t* address, const NodeMessage* message, uint8_t len, signed int rssi, bool broadcast) {
        (void)address;
        (void)len;
        (void)broadcast;

        bool legacyPacket = message->header.version == TUBES_PROTOCOL_V2;
        V3ProjectionTrailer projectionTrailer;
        bool legacyProjection = legacyPacket
            && readV3ProjectionTrailer(*message, projectionTrailer);
        if (legacyPacket) {
            if (!receiver->isValidV2Command(message->command, message->data))
                return;
            receiver->onV2PacketObserved(*message);
        } else if (isKnownTubesChannel(message->command)) {
            const TubesChannelPayload& payload = *reinterpret_cast<const TubesChannelPayload*>(message->data);
            if (!receiver->isValidV3Channel(
                    message->command,
                    payload,
                    message->header,
                    message->recipients))
                return;
        } else if (isKnownV3Topic(message->command)) {
            const V3TopicPayload& payload = *reinterpret_cast<const V3TopicPayload*>(message->data);
            if (!receiver->isValidV3Topic(
                    message->command,
                    payload,
                    message->header,
                    message->recipients,
                    rssi))
                return;
        }

        uint8_t incomingGeneration = protocolGenerationFromId(message->header.id);

        // Unknown future v3 topics may pass through an established route, but they
        // cannot change this firmware's topology or radio diagnostics.
        bool compatibleGenerationPacket = !legacyPacket
            && incomingGeneration >= CURRENT_PROTOCOL_GENERATION;
        if (compatibleGenerationPacket
            && (isKnownTubesChannel(message->command)
                || isKnownV3Topic(message->command))) {
            lastRssi = rssi;
            onPeerPing(message->header);
        } else if (legacyPacket) {
            // V2 nodes never participate in native V3 Control election. They can still
            // make this V3 node relay for them through its translated legacy identity.
            MeshNodeHeader translated = legacyHeader();
            if (shouldRenewRelayDuty(translated, message->header))
                rebroadcastTimer.start(REBROADCAST_TIME);
        }

        MeshNodeHeader routeHeader = legacyPacket ? legacyHeader() : nativeHeader();
        MeshRoutePlan route = planMeshRoute(routeHeader, isFollowing(), isLeading(), *message);
        if (!route.accepted) {
#ifdef NODE_DEBUGGING
            Serial.print("  -- ignored ");
            printMessage(message, rssi);
            Serial.println();
#endif
            return;
        }

        // Apply only at the root on the upward trip, then at every follower on the declaration trip.
        if (route.applyLocally) {
            bool traceMessage = serialTraceEnabled();
            if (traceMessage) {
                Serial.print("  >> ");
                printMessage(message, rssi);
                Serial.print(" ");
            }

            bool valid;
            if (message->header.version == TUBES_PROTOCOL_V3 && isKnownTubesChannel(message->command)) {
                const TubesChannelPayload& payload = *reinterpret_cast<const TubesChannelPayload*>(message->data);
                valid = receiver->onV3Channel(
                    message->command,
                    payload,
                    message->header,
                    message->recipients
                );
            } else if (message->header.version == TUBES_PROTOCOL_V3) {
                const V3TopicPayload& payload = *reinterpret_cast<const V3TopicPayload*>(message->data);
                valid = receiver->onV3Topic(
                    message->command,
                    payload,
                    message->header,
                    message->recipients,
                    rssi
                );
                // Unknown downward topics remain relayable so an older v3 relay does
                // not partition newer topic implementations from their followers.
                if (!valid && !isKnownV3Topic(message->command) && message->recipients == RECIPIENTS_ALL)
                    valid = true;
            } else
                valid = receiver->onV2Message(*message);
            if (traceMessage)
                Serial.println();

            if (!valid)
                return;

            // Clock synchronization follows successful application validation, so stale
            // authority packets and unknown topics cannot move the visual timebase.
            // A gen0 projection is carried for legacy descendants only; native
            // declarations remain the complete timing authority for gen1 receivers.
            if (route.synchronizeClock
                && (message->header.version == TUBES_PROTOCOL_V2
                    || isKnownTubesChannel(message->command)
                    || isKnownV3Topic(message->command))
                && !legacyProjection) {
                uint32_t new_timebase = message->timebase - millis() + 3; // Factor for network delay
                int32_t diff = new_timebase - strip.timebase;
                if (diff < -10 || diff > 10)
                    strip.timebase = new_timebase;
            }
        }

        // Preserve the accepted packet while advancing it one hop through the tree.
        if (route.relay) {
            NodeMessage msg = makeRelayedMessage(routeHeader, isFollowing(), *message);
            if (!isFollowing()
                && msg.header.version == TUBES_PROTOCOL_V3
                && isKnownTubesChannel(msg.command)
                && msg.recipients == RECIPIENTS_ALL) {
                TubesChannelPayload& payload = *reinterpret_cast<TubesChannelPayload*>(msg.data);
                if (payload.envelope.messageKind == ChannelRequest)
                    payload.envelope.messageKind = ChannelDeclaration;
            }
#ifdef NODE_DEBUGGING
            Serial.println("rebroadcast");
#endif
            broadcastMessage(&msg, true);
        }
    }

    // Validate, apply, and relay one variable-length generation-1 channel snapshot.
    // The Wi-Fi-task prefix filter has already rejected malformed lengths and framing.
    void onPeerChannelV2(
        const uint8_t* address,
        const TubesChannelMessageV2* message,
        uint8_t len,
        signed int rssi,
        bool broadcast
    ) {
        (void)address;
        (void)broadcast;
        if (!receiver->isValidV3ChannelV2(
                message->command,
                *message,
                message->header,
                message->recipients))
            return;

        lastRssi = rssi;
        onPeerPing(message->header);

        NodeMessage routeMessage;
        routeMessage.header = message->header;
        routeMessage.recipients = message->recipients;
        routeMessage.command = message->command;
        MeshNodeHeader routeHeader = nativeHeader();
        MeshRoutePlan route = planMeshRoute(
            routeHeader, isFollowing(), isLeading(), routeMessage);
        if (!route.accepted)
            return;

        if (route.applyLocally) {
            if (serialTraceEnabled()) {
                Serial.printf(
                    "  >> %04X/%04X v3 CHANNEL2-%02X[%04X/%04X k%u s%u] %ddB %uB ",
                    message->header.id,
                    message->header.uplinkId,
                    message->command,
                    message->envelope.channelId,
                    message->envelope.sourceControlId,
                    message->envelope.messageKind,
                    message->envelope.sequence,
                    rssi,
                    len
                );
            }
            if (!receiver->onV3ChannelV2(
                    message->command,
                    *message,
                    message->header,
                    message->recipients))
                return;
            if (serialTraceEnabled())
                Serial.println();
            if (route.synchronizeClock) {
                uint32_t newTimebase = message->timebase - millis() + 3;
                int32_t difference = newTimebase - strip.timebase;
                if (difference < -10 || difference > 10)
                    strip.timebase = newTimebase;
            }
        }

        if (route.relay) {
            TubesChannelMessageV2 relayed;
            memcpy(&relayed, message, len);
            relayed.header = routeHeader;
            if (!isFollowing()) {
                relayed.recipients = RECIPIENTS_ALL;
                relayed.envelope.messageKind = ChannelDeclaration;
            }
            relayed.timebase = strip.timebase + millis();
            if (isValidChannelMessageV2Prefix(
                    reinterpret_cast<const uint8_t*>(&relayed), len))
                espnowBroadcast.send(reinterpret_cast<const uint8_t*>(&relayed), len);
        }
    }
    // AI: end

    void broadcastMessage(NodeMessage *message, bool is_rebroadcast=false) {
        // Don't broadcast anything if this node isn't active.
        if (status != NODE_STATUS_STARTED) {
            if (status == NODE_STATUS_RECEIVING && statusTimer.ended()) {
                status = NODE_STATUS_STARTED;
                statusTimer.stop();
                Serial.printf("LightNode %s\n", status_code());
            } else {
                Serial.printf("broadcastMessage() - not started - %s\n", status_code());
                return;
            }
        }
        message->timebase = strip.timebase + millis();

#ifdef NODE_DEBUGGING
        Serial.print("  <<< ");
        printMessage(message, 0);
        Serial.println();
#endif

        __attribute__((unused)) auto success = espnowBroadcast.send((const uint8_t*)message, sizeof(*message));
#ifdef NODE_DEBUGGING
        if (!success) {
            Serial.println("espnowBroadcast.send() failed!");
        } else {
            Serial.println("successful broadcast");
        }
#endif

    }

