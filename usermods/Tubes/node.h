const char *command_name(CommandId command) {
    switch (command) {
        case COMMAND_STATE:
            return "UPDATE";
        case COMMAND_OPTIONS:
            return "OPTIONS";
        case COMMAND_ACTION:
            return "ACTION";
        case COMMAND_INFO:
            return "INFO";
        case COMMAND_BEATS:
            return "BEATS";
        default:
            return "?COMMAND?";
    }
}

class MessageReceiver {
  public:
    virtual bool onCommand(CommandId command, void *data) = 0;
    virtual bool onV2Message(const NodeMessage& message) = 0;
    virtual bool isValidV2Command(CommandId command, const uint8_t* data) const = 0;
    virtual bool isValidV3Topic(
        uint8_t topic,
        const V3TopicPayload& payload,
        const MeshNodeHeader& transportSender,
        MessageRecipients recipients,
        int8_t rssi
    ) const = 0;
    virtual bool onV3Topic(
        uint8_t topic,
        const V3TopicPayload& payload,
        const MeshNodeHeader& transportSender,
        MessageRecipients recipients,
        int8_t rssi
    ) = 0;
    virtual bool isValidV3Channel(
        uint8_t channel,
        const TubesChannelPayload& payload,
        const MeshNodeHeader& transportSender,
        MessageRecipients recipients
    ) const = 0;
    virtual bool onV3Channel(
        uint8_t channel,
        const TubesChannelPayload& payload,
        const MeshNodeHeader& transportSender,
        MessageRecipients recipients
    ) = 0;
    virtual bool isValidV3ChannelV2(
        uint8_t channel,
        const TubesChannelMessageV2& message,
        const MeshNodeHeader& transportSender,
        MessageRecipients recipients
    ) const = 0;
    virtual bool onV3ChannelV2(
        uint8_t channel,
        const TubesChannelMessageV2& message,
        const MeshNodeHeader& transportSender,
        MessageRecipients recipients
    ) = 0;
    virtual void onV2PacketObserved(const NodeMessage& message) = 0;
    virtual bool onButton(uint8_t button_id) = 0;
};

