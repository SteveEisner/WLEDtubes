  accum88 parse_number(const char *s) const {
    uint16_t whole = 0;
    uint16_t fraction = 0;

    while (*s == ' ') s++;
    while (*s >= '0' && *s <= '9')
      whole = whole * 10 + (*s++ - '0');
    whole <<= 8;

    if (*s == '.') {
      uint16_t divisor = 1;
      while (*++s >= '0' && *s <= '9') {
        fraction = fraction * 10 + (*s - '0');
        divisor *= 10;
      }
      fraction = (fraction << 8) / divisor;
    }
    return whole + fraction;
  }

