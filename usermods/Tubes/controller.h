  void update_beat() {
    current_state.bpm = next_state.bpm = beats.bpm;
    current_state.beat_frame = particle_beat_frame = beats.frac;  // (particle_beat_frame is a hack)
    if (current_state.bpm>>8 <= 118) // Hip hop / ghettofunk
      energy = MediumEnergy;
    else if (current_state.bpm>>8 >= 125) // House & breaks
      energy = HighEnergy;
    else if (current_state.bpm>>8 > 120) // Tech house
      energy = MediumEnergy;
    else
      energy = Chill; // Deep house
  }

  // AI: below section was generated by an AI
  // Applies a stable microphone estimate as the same complete clock state used by other Beat sources.
  void applyAutoTempoEstimate(const TempoEstimate& estimate) {
    if (!estimate.locked) {
      autoTempoClockLocked = false;
      if (node.serialTraceEnabled())
        Serial.println(F("AUTO_TEMPO unlocked; holding the last BPM"));
      return;
    }

    BeatFrame_24_8 frame = beats.frac;
    if (!autoTempoClockLocked)
      frame = estimate.beatOneFrame(frame);
    else if (estimate.phaseTracked && estimate.barTracked)
      frame = estimate.nearestBarFrame(frame);
    else if (estimate.phaseTracked)
      frame = estimate.nearestBeatFrame(frame);
    beats.sync(estimate.bpmQ8, frame);
    autoTempoClockLocked = true;
    update_beat();
    if (node.serialTraceEnabled())
      Serial.printf("AUTO_TEMPO bpm=%.2f confidence=%u phase=%u bar=%s%u/4 barConfidence=%u\n",
          estimate.bpmQ8 / 256.0f,
          estimate.confidence,
          estimate.beatPhase,
          estimate.barTracked ? "" : "?",
          estimate.beatInBar + 1,
          estimate.barConfidence);
  }
