  // Core WLED gradients were converted to linear values during the 16.0 color-pipeline change.
  static bool paletteUsesLegacyGammaEncoding(uint8_t paletteId) {
    return (paletteId >= 21 && paletteId <= 23)
        || (paletteId >= 33 && paletteId <= 34)
        || paletteId == 36
        || paletteId == 37
        || paletteId == 39
        || paletteId >= 48;
  }

  bool makePalette16(uint8_t paletteId, PaletteGradient16& definition) {
    if (paletteId >= gBuiltInPaletteCount)
      return false;
    CRGBPalette16 source;
    strip.getMainSegment().copyPalette(source, paletteId);
    bool convertToLinear = paletteUsesLegacyGammaEncoding(paletteId);
    for (uint8_t index = 0; index < 16; index++) {
      definition.rgb[index][0] = convertToLinear ? gamma8inv(source[index].r) : source[index].r;
      definition.rgb[index][1] = convertToLinear ? gamma8inv(source[index].g) : source[index].g;
      definition.rgb[index][2] = convertToLinear ? gamma8inv(source[index].b) : source[index].b;
    }
    return true;
  }

