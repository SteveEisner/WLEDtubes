  static bool parseGradientByte(const char*& cursor, char delimiter, uint8_t& value) {
    if (*cursor < '0' || *cursor > '9')
      return false;
    uint16_t parsed = 0;
    while (*cursor >= '0' && *cursor <= '9') {
      parsed = parsed * 10 + (*cursor++ - '0');
      if (parsed > UINT8_MAX)
        return false;
    }
    if (*cursor++ != delimiter)
      return false;
    value = parsed;
    return true;
  }

  static int8_t hexDigit(char value) {
    if (value >= '0' && value <= '9') return value - '0';
    if (value >= 'A' && value <= 'F') return value - 'A' + 10;
    if (value >= 'a' && value <= 'f') return value - 'a' + 10;
    return -1;
  }

  static bool parseGradientColor(const char*& cursor, PaletteGradientStop& stop) {
    uint32_t color = 0;
    for (uint8_t digit = 0; digit < 6; digit++) {
      if (!*cursor)
        return false;
      int8_t value = hexDigit(*cursor++);
      if (value < 0)
        return false;
      color = (color << 4) | value;
    }
    stop.red = color >> 16;
    stop.green = color >> 8;
    stop.blue = color;
    return true;
  }

  bool parseCustomGradient(const char* text, PaletteGradientDefinition& gradient) const {
    gradient = PaletteGradientDefinition();
    const char* cursor = text;
    while (*cursor && gradient.count < 8) {
      PaletteGradientStop& stop = gradient.stops[gradient.count];
      if (!parseGradientByte(cursor, ':', stop.position)
          || !parseGradientColor(cursor, stop))
        return false;
      gradient.count++;
      if (!*cursor)
        break;
      if (*cursor++ != ',')
        return false;
    }
    if (*cursor || gradient.count < 2)
      return false;
    PaletteGradient16 expanded;
    return expandPaletteGradient(gradient, expanded);
  }

  uint8_t nearestPaletteFallback(const PaletteGradientDefinition& gradient) {
    PaletteGradient16 literal;
    if (!expandPaletteGradient(gradient, literal))
      return 0;
    uint8_t nearest = 6;
    uint64_t nearestError = UINT64_MAX;
    for (uint16_t paletteId = 6; paletteId < gLegacyPaletteIdLimit; paletteId++) {
      CRGBPalette16 candidate;
      strip.getMainSegment().copyPalette(candidate, paletteId);
      uint64_t error = 0;
      for (uint8_t index = 0; index < 16; index++) {
        uint8_t position = index == 15 ? 255 : uint16_t(index) * 255 / 15;
        CRGB color = ColorFromPalette(candidate, position, 255, LINEARBLEND);
        int16_t red = int16_t(literal.rgb[index][0]) - color.r;
        int16_t green = int16_t(literal.rgb[index][1]) - color.g;
        int16_t blue = int16_t(literal.rgb[index][2]) - color.b;
        error += uint32_t(red * red) + uint32_t(green * green) + uint32_t(blue * blue);
      }
      if (error < nearestError) {
        nearestError = error;
        nearest = paletteId;
      }
    }
    return nearest;
  }

  // Finds a legacy-safe ID for a complete modern palette without exposing its source ID to gen0.
  uint8_t nearestPaletteFallback(const PaletteGradient16& literal) {
    uint8_t nearest = 6;
    uint64_t nearestError = UINT64_MAX;
    for (uint16_t paletteId = 6; paletteId < gLegacyPaletteIdLimit; paletteId++) {
      PaletteGradient16 candidate;
      if (!makePalette16(paletteId, candidate))
        continue;
      uint64_t error = 0;
      for (uint8_t index = 0; index < 16; index++) {
        for (uint8_t component = 0; component < 3; component++) {
          int16_t delta = int16_t(literal.rgb[index][component])
              - candidate.rgb[index][component];
          error += uint32_t(delta * delta);
        }
      }
      if (error < nearestError) {
        nearestError = error;
        nearest = paletteId;
      }
    }
    return nearest;
  }

