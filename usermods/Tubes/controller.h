  // Reserve one runtime-only WLED palette slot; updating it never writes LittleFS.
  void registerV3RuntimePalette() {
    removeUsermodPalettes(tubesV3PaletteName);
    if (usermodPalettes.size() >= WLED_MAX_USERMOD_PALETTES) {
      Serial.println(F("Tubes v3: no runtime palette slot available"));
      v3RuntimePaletteId = 0;
      return;
    }

    uint8_t paletteIndex = usermodPalettes.size();
    usermodPalettes.push_back({CRGBPalette16(CRGB::Black), tubesV3PaletteName, 0, nullptr});
    v3RuntimePaletteId = WLED_USERMOD_PALETTE_ID_BASE - paletteIndex;
  }

  // AI: below section was generated by an AI
  // Returns the WLED-owned runtime palette slot reserved by Tubes.
  CRGBPalette16* runtimeV3Palette() {
    if (!v3RuntimePaletteId)
      return nullptr;
    uint8_t paletteIndex = WLED_USERMOD_PALETTE_ID_BASE - v3RuntimePaletteId;
    if (paletteIndex >= usermodPalettes.size())
      return nullptr;
    return &usermodPalettes[paletteIndex].palette;
  }

  // Updates the reused WLED palette slot after preserving its old contents for WLED's transition.
  bool installRuntimeV3Palette(const uint8_t (&rgb)[16][3]) {
    CRGBPalette16* runtimePalette = runtimeV3Palette();
    if (!runtimePalette)
      return false;

    bool changed = false;
    for (uint8_t index = 0; index < 16; index++) {
      const CRGB& current = (*runtimePalette)[index];
      changed |= current.r != rgb[index][0]
          || current.g != rgb[index][1]
          || current.b != rgb[index][2];
    }
    if (changed && v3RuntimePaletteActive) {
      Segment& segment = strip.getMainSegment();
      if (segment.palette == v3RuntimePaletteId)
        segment.startTransition(transitionDelay, false);
    }

    for (uint8_t index = 0; index < 16; index++) {
      (*runtimePalette)[index] = CRGB(
          rgb[index][0],
          rgb[index][1],
          rgb[index][2]
      );
    }
    return true;
  }
