  bool makePaletteChannelSnapshot(PaletteChannelSnapshot& snapshot) {
    snapshot.state = currentPaletteChannelState();
    snapshot.transitionMs = transitionDelay;
    snapshot.currentHoldPhrases = currentPaletteHoldPhrases;
    snapshot.nextHoldPhrases = nextPaletteHoldPhrases;
    if (v3RuntimePaletteActive) {
      CRGBPalette16* runtimePalette = runtimeV3Palette();
      if (!runtimePalette)
        return false;
      for (uint8_t index = 0; index < 16; index++) {
        snapshot.currentDefinition.rgb[index][0] = (*runtimePalette)[index].r;
        snapshot.currentDefinition.rgb[index][1] = (*runtimePalette)[index].g;
        snapshot.currentDefinition.rgb[index][2] = (*runtimePalette)[index].b;
      }
    } else if (!makePalette16(snapshot.state.current.paletteId, snapshot.currentDefinition)) {
      return false;
    }

    if (nextPalette16Valid
        && nextPalette16Phrase == snapshot.state.next.palettePhrase
        && nextPalette16Fallback == snapshot.state.next.paletteId)
      snapshot.nextDefinition = nextPalette16;
    else if (!makePalette16(snapshot.state.next.paletteId, snapshot.nextDefinition))
      return false;
    nextPalette16 = snapshot.nextDefinition;
    nextPalette16Phrase = snapshot.state.next.palettePhrase;
    nextPalette16Fallback = snapshot.state.next.paletteId;
    nextPalette16Valid = true;
    return true;
  }

  // Publish one complete current-and-next snapshot. Authority changes delivery
  // direction, while every accepted packet remains independently recoverable.
  bool publishApplicationChannel(uint8_t channel) {
    uint32_t nowMs = millis();
    if (!channelWinners.localMayRequest(channel, localChannelId(channel), node.header.id, nowMs))
      return false;

    uint16_t beatPhrase = beats.frac >> TUBES_BEAT_FRAME_PHRASE_SHIFT;
    if (channel == BeatChannel
        && (!isTubesMeasureDownbeat(beats.frac) || beatPhrase == lastPublishedBeatPhrase))
      return false;

    TubesChannelMessageV2 message;
    bool prepared = false;
    if (channel == BeatChannel) {
      BeatChannelSnapshot snapshot;
      snapshot.state = currentBeatChannelState();
      snapshot.soundProgram = currentBeatSoundProgramExtension();
      snapshot.transient = currentBeatTransient;
      prepared = prepareChannelMessageV2(channel, ChannelRequest, snapshot, message);
    } else if (channel == PatternChannel) {
      PatternChannelSnapshot snapshot = currentPatternChannelSnapshot();
      prepared = prepareChannelMessageV2(channel, ChannelRequest, snapshot, message);
    } else if (channel == PaletteChannel) {
      PaletteChannelSnapshot snapshot;
      prepared = makePaletteChannelSnapshot(snapshot)
          && prepareChannelMessageV2(channel, ChannelRequest, snapshot, message);
    }
    if (!prepared)
      return false;

    if (!node.isFollowing()) {
      if (!channelWinners.acceptRequest(channel, message.envelope, nowMs))
        return false;
      message.envelope.messageKind = ChannelDeclaration;
    }
    bool sent = node.sendV3ChannelV2(channel, message);
    if (sent && channel == BeatChannel)
      lastPublishedBeatPhrase = beatPhrase;
    return sent;
  }

  bool publishApplicationChannelV1(uint8_t channel) {
    uint32_t nowMs = millis();
    if (!channelWinners.localMayRequest(channel, localChannelId(channel), node.header.id, nowMs))
      return false;

    auto publish = [this, channel, nowMs](TubesChannelPayload& payload) {
      if (node.isFollowing())
        return node.sendV3Channel(channel, payload);

      if (!channelWinners.acceptRequest(channel, payload.envelope, nowMs))
        return false;
      payload.envelope.messageKind = ChannelDeclaration;
      if (channel != PaletteChannel
          || payload.envelope.bodyLength == sizeof(PaletteChannelSchedule))
        channelSnapshots[channelIndex(channel)] = payload;
      return node.sendV3Channel(channel, payload);
    };

    if (channel == BeatChannel) {
      return false;
    } else if (channel == PatternChannel) {
      PatternChannelState state = currentPatternChannelState();
      TubesChannelPayload payload = makeChannelPayload(channel, ChannelRequest, &state, sizeof(state));
      return publish(payload);
    } else {
      PaletteChannelState state = currentPaletteChannelState();
      PaletteGradient16 currentDefinition;
      if (v3RuntimePaletteActive) {
        CRGBPalette16* runtimePalette = runtimeV3Palette();
        if (!runtimePalette)
          return false;
        for (uint8_t index = 0; index < 16; index++) {
          currentDefinition.rgb[index][0] = (*runtimePalette)[index].r;
          currentDefinition.rgb[index][1] = (*runtimePalette)[index].g;
          currentDefinition.rgb[index][2] = (*runtimePalette)[index].b;
        }
      } else if (!makePalette16(state.current.paletteId, currentDefinition)) {
        return false;
      }

      PaletteGradient16 nextDefinition;
      if (nextPalette16Valid
          && nextPalette16Phrase == state.next.palettePhrase
          && nextPalette16Fallback == state.next.paletteId)
        nextDefinition = nextPalette16;
      else if (!makePalette16(state.next.paletteId, nextDefinition))
        return false;
      nextPalette16 = nextDefinition;
      nextPalette16Phrase = state.next.palettePhrase;
      nextPalette16Fallback = state.next.paletteId;
      nextPalette16Valid = true;

      TubesChannelPayload currentPayload = makeChannelPayload(
          channel, ChannelRequest, &currentDefinition, sizeof(currentDefinition));
      uint16_t currentSequence = currentPayload.envelope.sequence;
      if (!publish(currentPayload))
        return false;

      TubesChannelPayload nextPayload = makeChannelPayload(
          channel, ChannelRequest, &nextDefinition, sizeof(nextDefinition));
      uint16_t nextSequence = nextPayload.envelope.sequence;
      if (!publish(nextPayload))
        return false;

      PaletteChannelSchedule schedule;
      schedule.state = state;
      schedule.currentDefinitionSequence = currentSequence;
      schedule.nextDefinitionSequence = nextSequence;
      TubesChannelPayload schedulePayload = makeChannelPayload(
          channel, ChannelRequest, &schedule, sizeof(schedule));
      if (!publish(schedulePayload))
        return false;

      // Older generation-1 receivers understand only the ID-based Palette state.
      // Send that projection after the full definition; current receivers recognize
      // the source and relay it without replacing the runtime gradient.
      TubesChannelPayload legacyPayload = makeChannelPayload(
          channel, ChannelRequest, &state, sizeof(state));
      return publish(legacyPayload);
    }
  }

