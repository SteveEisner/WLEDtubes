  bool ensureSoundOverlaySegment() {
    if (strip.getMainSegmentId() == SOUND_OVERLAY_SEGMENT_ID
        || SOUND_OVERLAY_SEGMENT_ID >= strip.getMaxSegments()) {
      traceSoundOverlayFailure(F("reserved ID unavailable"));
      return false;
    }

    bool created = false;
    if (strip.getSegmentsNum() == SOUND_OVERLAY_SEGMENT_ID) {
      const Segment& base = strip.getMainSegment();
      strip.appendSegment(base.start, base.stop, base.startY, base.stopY);
      created = true;
    } else if (strip.getSegmentsNum() < SOUND_OVERLAY_SEGMENT_ID) {
      traceSoundOverlayFailure(F("missing base segment"));
      return false;
    }
    if (strip.getSegmentsNum() <= SOUND_OVERLAY_SEGMENT_ID) {
      traceSoundOverlayFailure(F("append rejected"));
      return false;
    }

    soundOverlaySegmentId = SOUND_OVERLAY_SEGMENT_ID;
    Segment& overlay = strip.getSegment(soundOverlaySegmentId);
    if (!overlay.isActive()) {
      const Segment& base = strip.getMainSegment();
      overlay.setGeometry(
          base.start,
          base.stop,
          base.grouping,
          base.spacing,
          base.offset,
          base.startY,
          base.stopY,
          base.map1D2D
      );
      created = true;
    }
    if (!overlay.isActive()) {
      traceSoundOverlayFailure(F("pixel buffer unavailable"));
      return false;
    }

    if (created || !soundOverlaySegmentInitialized) {
      overlay.selected = false;
      overlay.setOption(SEG_OPTION_ON, false);
      overlay.setOpacity(0);
      soundOverlaySegmentInitialized = true;
    }
    return true;
  }

  // Reports persistent reservation failures without flooding field-debug serial output.
  void traceSoundOverlayFailure(const __FlashStringHelper* reason) {
    uint32_t now = millis();
    if (!node.serialTraceEnabled() || now - lastSoundOverlayFailureTrace < 5000)
      return;
    lastSoundOverlayFailureTrace = now;
    Serial.print(F("SOUND_LAYER reserve failed: "));
    Serial.print(reason);
    Serial.printf(
        " segs=%u max=%u main=%u heap=%u error=%u\n",
        strip.getSegmentsNum(),
        strip.getMaxSegments(),
        strip.getMainSegmentId(),
        getFreeHeapSize(),
        errorFlag
    );
  }

  // Applies the scheduled sound program as a native WLED layer over the base renderer.
  void refreshSoundProgramLayer() {
    bool enabled = soundProgramEnabled(currentSoundProgram);
    sound.setOverlayChance(currentSoundProgramChance);
    if (sound.overlay != enabled)
      sound.setOverlay(enabled);
    // Internal Tubes patterns replace WLED's composited pixels, so retain the
    // original O1 volume overlay there and reserve segment 1 for WLED bases.
    bool useNativeSoundLayer = enabled && isShowingWled();
    sound.setProgramActive(useNativeSoundLayer);

    if (!useNativeSoundLayer || patternOverride || !shouldRenderTubes()) {
      if (soundOverlaySegmentId < strip.getSegmentsNum())
        strip.getSegment(soundOverlaySegmentId).setOption(SEG_OPTION_ON, false);
      return;
    }
    if (!ensureSoundOverlaySegment())
      return;

    const Segment& base = strip.getMainSegment();
    Segment& overlay = strip.getSegment(soundOverlaySegmentId);
    overlay.setGeometry(
        base.start,
        base.stop,
        base.grouping,
        base.spacing,
        base.offset,
        base.startY,
        base.stopY,
        base.map1D2D
    );
    // appendSegment() runs after WLED's normal capability scan, so refresh the
    // runtime-created segment before palette effects decide whether it supports RGB.
    overlay.refreshLightCapabilities();
    for (uint8_t slot = 0; slot < NUM_COLORS; slot++)
      overlay.setColor(slot, base.colors[slot]);
    overlay.setMode(currentSoundProgram.wledEffect);
    overlay.setPalette(currentSoundProgram.palette);
    overlay.speed = currentSoundProgram.speed;
    overlay.intensity = currentSoundProgram.intensity;
    overlay.custom1 = currentSoundProgram.custom1;
    overlay.custom2 = currentSoundProgram.custom2;
    overlay.custom3 = currentSoundProgram.custom3;
    overlay.check1 = currentSoundProgram.options & SoundProgramCheck1;
    overlay.check2 = currentSoundProgram.options & SoundProgramCheck2;
    overlay.check3 = currentSoundProgram.options & SoundProgramCheck3;
    overlay.blendMode = currentSoundProgram.blendMode;
    // The program runs continuously, but the Beat transient envelope controls visibility.
    overlay.opacity = sound.scaledAccentOpacity(currentSoundProgram.opacity);
    overlay.setOption(SEG_OPTION_ON, true);
    stateChanged = true;
  }

  // Updates runtime opacity without starting a WLED state transition on every audio sample.
  void updateSoundOverlayOpacity() {
    if (!sound.programActive || soundOverlaySegmentId >= strip.getSegmentsNum())
      return;
    strip.getSegment(soundOverlaySegmentId).opacity =
        sound.scaledAccentOpacity(currentSoundProgram.opacity);
  }

  // Applies each source's compact transient sequence once, even when mesh relays repeat it.
  void acceptBeatTransient(
      DeviceId sourceControlId,
      uint32_t sourceSession,
      const BeatTransientExtension& transient
  ) {
    bool sameSource = hasBeatTransientSequence
        && lastBeatTransientSource == sourceControlId
        && lastBeatTransientSession == sourceSession;
    if (sameSource && transient.sequence == lastBeatTransientSequence)
      return;
    hasBeatTransientSequence = true;
    lastBeatTransientSource = sourceControlId;
    lastBeatTransientSession = sourceSession;
    lastBeatTransientSequence = transient.sequence;
    if (sourceControlId == node.header.id
        || (!transient.kick && !transient.snare && !transient.music))
      return;
    SoundAccent accent;
    accent.kick = transient.kick;
    accent.snare = transient.snare;
    accent.music = transient.music;
    sound.tryApplyAccent(accent);
  }

