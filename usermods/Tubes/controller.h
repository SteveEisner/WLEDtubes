  void storePaletteDefinition(
      const TubesChannelEnvelope& envelope,
      const PaletteGradient16& definition
  ) {
    paletteDefinitionCache[1] = paletteDefinitionCache[0];
    PaletteChannelDefinitionCacheEntry& entry = paletteDefinitionCache[0];
    entry.valid = true;
    entry.channelId = envelope.channelId;
    entry.controlId = envelope.sourceControlId;
    entry.session = envelope.sourceSession;
    entry.sequence = envelope.sequence;
    entry.palette = definition;
  }

  const PaletteGradient16* findPaletteDefinition(
      const TubesChannelEnvelope& envelope,
      uint16_t sequence
  ) const {
    for (const PaletteChannelDefinitionCacheEntry& entry : paletteDefinitionCache) {
      if (entry.valid
          && entry.channelId == envelope.channelId
          && entry.controlId == envelope.sourceControlId
          && entry.session == envelope.sourceSession
          && entry.sequence == sequence)
        return &entry.palette;
    }
    return nullptr;
  }

