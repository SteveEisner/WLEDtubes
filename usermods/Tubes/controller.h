  void onAction(Action* action) {
    TubeOperation operation;
    if (!decodeOperation(action->key, action->arg, operation))
      return;
    if (tubeOperationScope(operation) == SelectedScope && !isOperationSelected())
      return;

    operation.tag &= 0x3F;
    executeOperation(operation);
  }

