  // Parses the complete O command; legacy ten-field commands default to full chance.
  bool parseSoundProgramEntry(
      const char* arguments,
      SoundProgramEntry& program,
      uint8_t& chance
  ) const {
    static constexpr uint8_t MIN_VALUE_COUNT = 10;
    static constexpr uint8_t MAX_VALUE_COUNT = 11;
    uint8_t values[MAX_VALUE_COUNT] = {0};
    const char* cursor = arguments;
    uint8_t count = 0;
    bool terminated = false;
    while (count < MAX_VALUE_COUNT) {
      if (!cursor || *cursor < '0' || *cursor > '9')
        return false;
      char* end = nullptr;
      unsigned long value = strtoul(cursor, &end, 10);
      if (end == cursor || value > UINT8_MAX)
        return false;
      values[count++] = uint8_t(value);
      if (*end == '\0') {
        terminated = true;
        break;
      }
      if (*end != ',')
        return false;
      cursor = end + 1;
    }
    if (count < MIN_VALUE_COUNT || !terminated)
      return false;

    if (values[0] >= strip.getModeCount()
        || values[7] > SoundProgramCheck1 + SoundProgramCheck2 + SoundProgramCheck3
        || values[8] > 16)
      return false;

    program = SoundProgramEntry();
    program.flags = SoundProgramEnabled;
    program.wledEffect = values[0];
    program.palette = values[1];
    program.speed = values[2];
    program.intensity = values[3];
    program.custom1 = values[4];
    program.custom2 = values[5];
    program.custom3 = values[6];
    program.options = values[7];
    program.blendMode = values[8];
    program.opacity = values[9];
    chance = count == MAX_VALUE_COUNT ? values[10] : SOUND_CHANCE_ALL;
    return true;
  }

  // AI: below section was generated by an AI
  // Parses a fixed number of bounded decimal fields without accepting partial input.
  static bool parseDecimalFields(
      const char* text,
      uint16_t* values,
      uint8_t count,
      uint16_t maximum
  ) {
    const char* cursor = text;
    for (uint8_t index = 0; index < count; index++) {
      if (!cursor || *cursor < '0' || *cursor > '9')
        return false;
      char* end = nullptr;
      unsigned long value = strtoul(cursor, &end, 10);
      if (end == cursor || value > maximum)
        return false;
      values[index] = uint16_t(value);
      if (index + 1 < count) {
        if (*end != ',')
          return false;
        cursor = end + 1;
      } else if (*end) {
        return false;
      }
    }
    return true;
  }

  // Parses pW and pT extended programs while retaining p### as the legacy table selector.
  bool parsePatternProgramEntry(const char* arguments, PatternProgramEntry& program) const {
    if (!arguments || (arguments[0] != 'W' && arguments[0] != 'T') || arguments[1] != ',')
      return false;
    program = PatternProgramEntry();
    if (arguments[0] == 'W') {
      static constexpr uint8_t VALUE_COUNT = 11;
      uint16_t values[VALUE_COUNT] = {0};
      if (!parseDecimalFields(arguments + 2, values, VALUE_COUNT, 1024))
        return false;
      if (values[0] >= strip.getModeCount()
          || values[1] > UINT8_MAX
          || values[2] > UINT8_MAX
          || values[3] > UINT8_MAX
          || values[4] > UINT8_MAX
          || values[5] > 31
          || values[6] > 7
          || values[7] > 7
          || (values[7] & ~values[6])
          || values[8] > SwingDrift
          || values[9] >= gPatternCount) {
        return false;
      }
      program.renderer = PatternRendererWled;
      program.renderId = values[0];
      program.speed = values[1];
      program.intensity = values[2];
      program.custom1 = values[3];
      program.custom2 = values[4];
      program.custom3 = values[5];
      program.optionMask = values[6];
      program.optionValues = values[7];
      program.syncMode = values[8];
      program.fallbackPatternId = values[9];
      program.holdPhrases = values[10];
      return true;
    }

    static constexpr uint8_t VALUE_COUNT = 4;
    uint16_t values[VALUE_COUNT] = {0};
    if (!parseDecimalFields(arguments + 2, values, VALUE_COUNT, 1024)
        || values[0] >= numInternalPatterns
        || values[1] > SwingDrift
        || values[2] >= gPatternCount)
      return false;
    program.renderer = PatternRendererTubes;
    program.renderId = values[0];
    program.syncMode = values[1];
    program.fallbackPatternId = values[2];
    program.holdPhrases = values[3];
    program.speed = 128;
    program.intensity = 128;
    return true;
  }

